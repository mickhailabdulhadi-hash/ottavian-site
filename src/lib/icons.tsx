// ─── App icon badge ───────────────────────────────────────────────────────────
// Normalized: rounded-square, Charcoal Raised bg, Clay-tinted monogram

export function AppBadge({ name, size = 40 }: { name: string; size?: number }) {
  const initials = name.replace(/[^a-zA-Z0-9]/g, "").slice(0, 2).toUpperCase();
  const radius = Math.round(size * 0.22);
  return (
    <div
      className="flex items-center justify-center shrink-0"
      style={{
        width: size, height: size,
        borderRadius: radius,
        background: "rgba(197,106,68,0.13)",
        border: "1px solid rgba(197,106,68,0.18)",
      }}
    >
      <span style={{ fontFamily: "var(--font-mono)", fontWeight: 500, fontSize: Math.round(size * 0.3) + "px", color: "#C56A44", lineHeight: 1 }}>
        {initials}
      </span>
    </div>
  );
}

export function StatusDot({ status }: { status: "running" | "stopped" | "deploying" }) {
  const c = { running: "#4ade80", stopped: "#6b7280", deploying: "#C56A44" };
  return <span className="inline-block w-1.5 h-1.5 rounded-full shrink-0" style={{ background: c[status] }} />;
}

